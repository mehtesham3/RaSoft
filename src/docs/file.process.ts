import { Injectable, InternalServerErrorException } from '@nestjs/common';
import * as fs from 'fs/promises';
import * as path from 'path';
import pdf from '@cedrugs/pdf-parse';
import * as mamoth from 'mammoth';
import { RecursiveCharacterTextSplitter } from '@langchain/textsplitters';
import { Repository } from 'typeorm';
import { Chunk } from '../schema/chunk.js';
import { InjectRepository } from '@nestjs/typeorm';
import { GoogleGenAI } from '@google/genai';

@Injectable()
export class FileProcessService {
  private google: GoogleGenAI;
  constructor(@InjectRepository(Chunk) private chunkModule: Repository<Chunk>) {
    this.google = new GoogleGenAI({ apiKey: process.env.GOOGLE_API_KEY });
  }

  async extractText(filepath: string): Promise<string> {
    const ext = path.extname(filepath).toLowerCase();

    switch (ext) {
      case '.txt':
      case '.md':
        return fs.readFile(filepath, 'utf-8');
      case '.pdf':
        const dataBuffer = await fs.readFile(filepath);
        const pdfData = await pdf(dataBuffer);
        if (!pdfData.text) throw new Error('Failed to extract text from PDF');
        return pdfData.text;
      case '.docx':
        const docxBuffer = await fs.readFile(filepath);
        const docxData = await mamoth.extractRawText({ buffer: docxBuffer });
        if (!docxData.value)
          throw new Error('Failed to extract text from DOCX');
        return docxData.value;
      default:
        throw new Error('Unsupported file type : ' + ext);
    }
  }

  async splitText(
    text: string,
    chunkSize: number = 550,
    chunkOverlap: number = 70,
  ): Promise<string[]> {
    const splitter = new RecursiveCharacterTextSplitter({
      chunkSize,
      chunkOverlap,
      separators: ['\n\n', '\n', ' ', ''],
    });

    if (chunkSize <= chunkOverlap) {
      throw new Error('Chunk size must be greater than chunk overlap');
    }
    const chunks = await splitter.splitText(text);

    return chunks;
  }

  async genEmbedding(chunks: string[], documentId: string, tenanId: string) {
    if (!chunks || chunks.length === 0) {
      throw new Error('No chunks provided for embedding');
    }
    try {
      const startTime = Date.now();
      const embedding = await this.google.models.embedContent({
        model: 'gemini-embedding-001',
        contents: chunks,
        config: {
          outputDimensionality: 1536,
          // Add any other config options you need
        },
      });

      const embeddingList = Array.isArray(embedding.embeddings)
        ? embedding.embeddings
        : [embedding.embeddings];

      if (embeddingList.length !== chunks.length) {
        throw new Error(
          `Embedding count (${embeddingList.length}) does not match chunk count (${chunks.length})`,
        );
      }

      const entitiesToSave: any = chunks.map((text, index) => {
        const vectorValues = embeddingList[index]?.values;

        if (!vectorValues || vectorValues.length === 0) {
          throw new Error(`Missing embedding for chunk ${index}`);
        }

        return this.chunkModule.create({
          Chunk: text,
          documentId: documentId,
          tenantId: tenanId,
          embedding: vectorValues,
        });
      });

      const endingTime = Date.now();
      const duration = endingTime - startTime;
      console.log(`Embedding took ${duration}ms`);

      const savedChunks = await this.chunkModule.save(entitiesToSave);

      console.log(`Successfully embedded generated by Google Embeddings. `);

      return { savedChunks, duration };
    } catch (error) {
      console.error('Error during Google embedding ingestion pipeline:', error);
      throw new InternalServerErrorException(
        'Failed to process and store text chunks.',
      );
    }
  }
}
